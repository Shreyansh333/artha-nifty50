import { useState } from "react";
import { Link } from "react-router-dom";
import { ChevronDown, Minus, TrendingDown, TrendingUp } from "lucide-react";
import { Badge, Segmented, cx } from "../../components/ui";
import { byUnit } from "../../lib/format";
import { useSettings } from "../../lib/store";
import type { Company, Insight } from "../../lib/types";

export function InsightCard({ o, compact = false, showSymbol = false }: { o: Insight; compact?: boolean; showSymbol?: boolean }) {
  const [open, setOpen] = useState(!compact);
  const unit = useSettings((s) => s.unit);
  const Icon = o.tone === "positive" ? TrendingUp : o.tone === "negative" ? TrendingDown : Minus;
  const toneCls = o.tone === "positive" ? "text-up bg-up/10" : o.tone === "negative" ? "text-down bg-down/10" : "text-ink2 bg-raised";
  return (
    <article className="rounded-xl border border-line bg-raised/30 p-3 transition hover:border-ink3/40">
      <button className="flex w-full items-start gap-3 text-left" onClick={() => setOpen((x) => !x)} aria-expanded={open}>
        <span className={cx("mt-0.5 flex h-6 w-6 shrink-0 items-center justify-center rounded-lg", toneCls)}><Icon size={13} /></span>
        <span className="min-w-0 flex-1">
          <span className="flex flex-wrap items-center gap-1.5">
            {showSymbol && <Link to={`/company/${o.symbol}/insights`} onClick={(e) => e.stopPropagation()} className="font-mono text-2xs font-semibold text-accent hover:underline">{o.symbol}</Link>}
            <span className="text-xs font-medium text-ink">{o.title}</span>
          </span>
          <span className="mt-0.5 flex flex-wrap gap-1.5 text-2xs text-ink3"><span>{o.category}</span>·<span>{o.period}</span></span>
        </span>
        <ChevronDown size={14} className={cx("mt-1 shrink-0 text-ink3 transition", open && "rotate-180")} />
      </button>
      {open && (
        <div className="mt-3 space-y-2 pl-9 animate-fade">
          <p className="text-xs leading-relaxed text-ink2"><Badge>Fact</Badge> <span className="ml-1">{o.fact}</span></p>
          {o.interpretation && (
            <p className="text-xs italic leading-relaxed text-ink3"><Badge tone="accent">Interpretation</Badge> <span className="ml-1">{o.interpretation}</span></p>
          )}
          {o.evidence.length > 0 && (
            <div className="grid grid-cols-2 gap-x-4 gap-y-1 rounded-lg border border-line/70 bg-surface/60 p-2 sm:grid-cols-3">
              {o.evidence.map((e) => (
                <div key={e.label} className="min-w-0">
                  <div className="truncate text-2xs text-ink3">{e.label}</div>
                  <div className="num text-xs text-ink">{byUnit(e.value, e.unit === "n" ? "n" : e.unit, unit)}</div>
                </div>
              ))}
            </div>
          )}
          {o.threshold && <p className="text-2xs text-ink3">Rule <span className="font-mono">{o.rule}</span>: triggered when {o.threshold}.</p>}
        </div>
      )}
    </article>
  );
}

export default function InsightsTab({ c }: { c: Company }) {
  const [tone, setTone] = useState<"all" | "positive" | "negative" | "neutral">("all");
  const cats = Array.from(new Set(c.insights.map((i) => i.category)));
  const [cat, setCat] = useState("all");
  const list = c.insights.filter((i) => (tone === "all" || i.tone === tone) && (cat === "all" || i.category === cat)).sort((a, b) => b.weight - a.weight);
  return (
    <div className="space-y-4">
      <div className="card p-4 text-xs leading-relaxed text-ink2">
        Observations are generated by deterministic rules over this company's computed statements, KPIs and market data —
        no language model writes or alters them. Each shows the exact evidence and the rule threshold. <b className="text-ink">Facts</b> are directly verifiable;
        <b className="text-accent"> interpretations</b> are standard analytical readings, not investment recommendations.
      </div>
      <div className="flex flex-wrap gap-2">
        <Segmented value={tone} onChange={setTone} options={[{ value: "all", label: `All (${c.insights.length})` }, { value: "positive", label: "Positive" }, { value: "negative", label: "Negative" }, { value: "neutral", label: "Neutral" }]} />
        <Segmented value={cat} onChange={setCat} options={[{ value: "all", label: "All categories" }, ...cats.map((x) => ({ value: x, label: x }))]} />
      </div>
      <div className="grid gap-3 lg:grid-cols-2">{list.map((o) => <InsightCard key={o.rule + o.period} o={o} />)}</div>
      {list.length === 0 && <div className="card p-6 text-center text-xs text-ink3">No observations match these filters.</div>}
    </div>
  );
}
